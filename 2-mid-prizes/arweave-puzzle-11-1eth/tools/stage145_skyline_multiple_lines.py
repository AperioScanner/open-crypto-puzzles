#!/usr/bin/env python3
"""A11-EXP-145 — is reversed-image "spire" made from multiple native shoreline lines?

Stage144 tested removal of ONE selected long horizontal component and found
8/12 skyline x-blocks still supported, even after fixing a partial-cut defect.
This is a bounded, distinct observable: are at least TWO y-separated source
horizontal-rule bands visible and robust across lossy source formats?

An isolated artificial single baseline, TWO parallel lines, and buildings
without long baselines are calibrated as separate synthetic controls. No
thresholds are selected from real-image significance. Both Stage144 source
measurements and the repaired positive/negative calibration must reproduce.

A copied/rotated/mirrored central spire can be generated by horizontally
drawn lines, but this test never claims that any transformed shape is a
unique chess figure or key. No OCR, BIP39, words, wallet or external content.
"""
from __future__ import annotations
import hashlib
import json
from pathlib import Path

import cv2
import numpy as np
from PIL import Image, ImageDraw

from stage112_corrected_sail_width_progression import variants
from stage144_rotated_skyline_spire import (
    SHA, X0, X1, Y0, Y1, FORMATS, N_BLOCKS, LOCAL_Y_RADIUS,
    long_horizontal, evaluate as stage144_evaluate,
    scored_line, strip, synthetic as legacy_synthetic, mirror_pair,
)

ROOT=Path(__file__).resolve().parents[1]
PNG=ROOT/"clues"/"arweave-puzzle-11.png"
STAGE144=ROOT/"analysis"/"runs"/"stage144-rotated-skyline-spire"/"result.json"
OUT=ROOT/"analysis"/"runs"/"stage145-skyline-multi-horizontal"
OUT.mkdir(parents=True,exist_ok=True)

# All thresholds chosen before executing this source experiment:
MIN_BAND_X_BLOCKS=6
MIN_DISTINCT_Y_GAP=15
MAX_HOLE_Y=2
MAX_STAGE144_DIFFERENCE=0
REQUIRE_STAGE144_RESIDUAL_BLOCKS=6
SYNTHETIC_EXTRA_LINE_YS=(239,281)
BLANK_LINE_Y=260

def row_support(opened):
    h,w=opened.shape
    rows=[]
    for y in range(LOCAL_Y_RADIUS,h-LOCAL_Y_RADIUS):
        cell=[]
        for k in range(N_BLOCKS):
            x0=k*w//N_BLOCKS
            x1=(k+1)*w//N_BLOCKS
            cell.append(int(np.any(opened[y-LOCAL_Y_RADIUS:y+LOCAL_Y_RADIUS+1,x0:x1]>0)))
        rows.append({"y":int(Y0+y),"support_blocks":int(sum(cell))})
    return rows

def continuous_groups(supported):
    """Find source-separated horizontal bands, not just contiguous lines.

    The morphology-supplied line mask is given; this groups y rows with at
    least six skyline x-blocks of horizontal ink and at most two missing rows.
    """
    valid=[r for r in supported if r["support_blocks"]>=MIN_BAND_X_BLOCKS]
    groups=[]
    for row in valid:
        if groups and row["y"]-groups[-1][-1]["y"]<=MAX_HOLE_Y+1:
            groups[-1].append(row)
        else:
            groups.append([row])
    result=[]
    for g in groups:
        highest=max(g,key=lambda r:(r["support_blocks"],-r["y"]))
        center=int(round(np.mean([r["y"] for r in g])))
        result.append({
           "from_y":g[0]["y"],"to_y":g[-1]["y"],
           "center_y":center,
           "peak_y":highest["y"],
           "max_horizontal_support_blocks":highest["support_blocks"],
           "rows":len(g),
        })
    return result

def distinct_two(groups):
    for i,a in enumerate(groups):
        for b in groups[i+1:]:
            if abs(a["center_y"]-b["center_y"])>=MIN_DISTINCT_Y_GAP:
                return True
    return False

def evaluate(img):
    opened=long_horizontal(img)
    raw_groups=continuous_groups(row_support(opened))
    stage144=stage144_evaluate(img)
    best,_=scored_line(img)
    cleaned=strip(img,best)
    residual=continuous_groups(row_support(long_horizontal(cleaned)))
    new_source_line=bool(
       distinct_two(raw_groups)
       and stage144["post_horizontal_rule_removal_blocks"]>=REQUIRE_STAGE144_RESIDUAL_BLOCKS
       and len(residual)>=1
    )
    return {
      "long_horizontal_y_groups":raw_groups,
      "remaining_y_groups_after_stage144_single_stroke_ablation":residual,
      "original_stage144":stage144,
      "two_independent_skyline_horizon_bands":new_source_line,
    }

def example_two_line_scene():
    # The one-line fixture from Stage144 is intentionally replaced by
    # TWO source lines separated more than 15 y pixels.
    img=legacy_synthetic(False)
    for y in SYNTHETIC_EXTRA_LINE_YS:
        for x in range(X0,X1-13,67):
            cv2.line(img,(x,y),(min(X1-1,x+58),y),
                     0,2,cv2.LINE_AA)
    return img

def control_suite():
    configurations=(
        ("multiple_parallel_lines", example_two_line_scene(),True),
        ("single_baseline",legacy_synthetic(True),False),
        ("facades_no_long_baseline",legacy_synthetic(False),False)
    )
    results={}
    passed=0
    for name,source,expected in configurations:
        results[name]={}
        for fmt,frame in variants(source).items():
            if fmt not in FORMATS:continue
            observed=evaluate(frame)
            actual=observed["two_independent_skyline_horizon_bands"]
            correct=bool(actual==expected)
            results[name][fmt]={
              "expected_multi":expected,
              "actual_multi":actual,
              "pass":correct,
              "bands":[{"y":p["center_y"],"blocks":p["max_horizontal_support_blocks"]}
                       for p in observed["long_horizontal_y_groups"]],
              "post_selected_horizon_support":observed["original_stage144"]["post_horizontal_rule_removal_blocks"],
            }
            passed+=int(correct)
    return {
       "passed":passed==12,
       "cases":12,
       "passed_cases":passed,
       "experiments":results,
    }

def source_reproduction(real,old):
    if old["source_sha256"]!=SHA or not old["controls"]["pass"]:
        return False
    for fmt in FORMATS:
        a=real[fmt]["original_stage144"]
        b=old["source_variants"][fmt]
        for key in ("best_source_horizon_y","source_horizontal_support_blocks",
                    "post_horizontal_rule_removal_blocks",
                    "source_blocks_lost_by_ablation",
                    "unmodified_source_rule_explains_vertical_spire"):
            if a[key]!=b[key]:
                return False
    return True

def full_horizontal_ablation(gray):
    out=gray.copy()
    detected=long_horizontal(gray)
    # Diagnostic counterfactual only: strip ALL independently pre-existing
    # long horizontal source strokes in the SAME Stage144 source window.
    mask=cv2.dilate(detected,np.ones((3,3),np.uint8),iterations=1)
    piece=out[Y0:Y1,X0:X1]
    piece[mask>0]=255
    return out

def save_contacts(original):
    crop=lambda z:z[0:330,X0:X1]
    previous_best,_=scored_line(original)
    single=strip(original,previous_best)
    all_removed=full_horizontal_ablation(original)
    variants_show=(
        ("source rotated+mirrored",original),
        ("one complete line removed",single),
        ("all native long source lines removed",all_removed),
    )
    width,height=560,690
    sheet=Image.new("RGB",(width*3,height+38),"white")
    draw=ImageDraw.Draw(sheet)
    for i,(label,img) in enumerate(variants_show):
        picture=mirror_pair(crop(img),True)
        pil=Image.fromarray(picture).resize((width,height)).convert("RGB")
        sheet.paste(pil,(i*width,38))
        draw.text((6+i*width,8),label,fill=(0,0,0))
    sheet.save(OUT/"spire-multiple-source-lines-ablation.png")

def main():
    digest=hashlib.sha256(PNG.read_bytes()).hexdigest()
    if digest!=SHA:raise RuntimeError("Canonical PNG hash mismatch")
    img=np.asarray(Image.open(PNG).convert("L"))
    if img.shape!=(1105,1600):raise RuntimeError("Unexpected image dimensions")
    old=json.loads(STAGE144.read_text())
    control=control_suite()
    by_variant={v:evaluate(a) for v,a in variants(img).items() if v in FORMATS}
    prior_pass=source_reproduction(by_variant,old)
    stable=all(by_variant[v]["two_independent_skyline_horizon_bands"]
               for v in FORMATS)
    decision=(
       "CONTROL_FAILURE" if not control["passed"] else
       "STAGE144_REPRODUCTION_FAILURE" if not prior_pass else
       "MULTIPLE_NATIVE_HORIZON_LINES_SUPPORT_SPIRE"
       if stable else
       "NO_REPLICATED_MULTIPLE_HORIZONTAL_RULES"
    )
    result={
      "experiment_id":"A11-EXP-145",
      "date":"2026-10-13",
      "hypothesis":"the apparent vertical axis in user's reversed skyline mirror arises from MORE THAN ONE original horizontal waterfront pencil stroke, rather than one continuous original source line",
      "evidence":"Repaired Stage144 single-component ablation leaves 8/12 x-blocks of valid long horizontal source strokes under every source/JPEG rendering; center y258-260 stable",
      "scope":"same unmodified Stage144 canonical x180..1595 y225..292 source region, same 35px morphological horizontal filter, 12 x-blocks, 4 image formats; analyze separated y bands and first-component ablation",
      "sha256":digest,
      "criteria":{"minimum_support_blocks_per_band":MIN_BAND_X_BLOCKS,
                  "minimum_band_separation_y":MIN_DISTINCT_Y_GAP,
                  "maximum_missing_band_rows":MAX_HOLE_Y,
                  "minimum_residual_after_first_line":REQUIRE_STAGE144_RESIDUAL_BLOCKS},
      "controls":control,
      "stage144_exact_reproduction":prior_pass,
      "by_variant":by_variant,
      "multi_band_all_four_variants":stable,
      "decision":decision,
      "interpretation_guard":"A positive only verifies native multiple long horizontal ink bands that rotate into the user's apparent black vertical axis. Symmetric shape is user-created by flip; neither a chess/tower code nor proof of intentional steganography. Negative limits solely fixed horizontal line-band test.",
      "safety_guard":"No private keys, BIP39, wallets, Ethereum, mnemonic words, secret candidates, off-image sources or social media."
    }
    save_contacts(img)
    (OUT/"result.json").write_text(json.dumps(result,indent=2)+"\n")
    report=[
      "# Stage145 — multiple horizontal waterfront strokes under apparent spire","",
      f"- Canonical original PNG hash: **{digest==SHA}**",
      f"- Two-line / one-line / no-line synthetic controls: **{control['passed_cases']}/{control['cases']}**",
      f"- Reproduces corrected Stage144 source metrics exactly: **{prior_pass}**",
      f"- Two separated skyline line bands confirmed in all four renders: **{stable}**",
      f"- Decision: **{decision}**","",
      "| format | distinct source y bands | remaining after first-line cut |",
      "|---|---|---|"
    ]
    for v in FORMATS:
        z=by_variant[v]
        positions=[p["center_y"] for p in z["long_horizontal_y_groups"]]
        remaining=z["original_stage144"]["post_horizontal_rule_removal_blocks"]
        report.append(f"| {v} | {positions} | {remaining}/12 blocks |")
    report+=["","## Interpretation",""]
    if not control["passed"] or not prior_pass:
        report.append("Synthetic controls or Stage144 source reproduction failed. Repair Stage145.")
    elif stable:
        report.append("More than one independent native horizontal pencil band contributes to the apparent vertical motif after rotation. This explains a source mechanism, not a unique symbol.")
    else:
        report.append("The fixed band-separation test does not confirm multiple independent horizontal source rules across all renderings. No spire or tower code is established.")
    report+=["","Contact: spire-multiple-source-lines-ablation.png. No secret material.",""]
    (OUT/"REPORT.md").write_text("\n".join(report))
    print(json.dumps({"stage":145,"controls":control["passed"],
                      "prior":prior_pass,"multi":stable,"decision":decision}))

if __name__=="__main__":main()
